"""Generates icons, extension/branding.js and branding.iss from branding/branding.json and branding/logo.png."""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAND_DIR = os.path.join(ROOT, "branding")
EXT_DIR = os.path.join(ROOT, "extension")

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print("Installing Pillow (image library)...")
    subprocess.check_call([sys.executable, "-m", "pip", "install", "pillow"])
    from PIL import Image, ImageDraw, ImageFont


def font(size):
    for name in ("arialbd.ttf", "Arial Bold.ttf", "DejaVuSans-Bold.ttf",
                 "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    return ImageFont.load_default()


def default_logo(path):
    s = 512
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle((0, 0, s - 1, s - 1), radius=112, fill=(209, 0, 0, 255))
    f = font(250)
    box = d.textbbox((0, 0), "4K", font=f)
    d.text(((s - (box[2] - box[0])) / 2 - box[0], 70 - box[1]), "4K", font=f, fill="white")
    cx = s // 2
    d.rectangle((cx - 26, 340, cx + 26, 400), fill="white")
    d.polygon([(cx - 80, 392), (cx + 80, 392), (cx, 468)], fill="white")
    img.save(path)


def make_square(img):
    img = img.convert("RGBA")
    side = max(img.size)
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(img, ((side - img.width) // 2, (side - img.height) // 2), img)
    return canvas


def main():
    with open(os.path.join(BRAND_DIR, "branding.json"), encoding="utf-8") as f:
        b = json.load(f)
    logo_path = os.path.join(BRAND_DIR, "logo.png")
    if not os.path.isfile(logo_path):
        print("No branding/logo.png found: creating a default logo.")
        default_logo(logo_path)

    logo = make_square(Image.open(logo_path))
    big = logo.resize((256, 256), Image.LANCZOS)

    os.makedirs(os.path.join(EXT_DIR, "icons"), exist_ok=True)
    for n in (16, 48, 128):
        logo.resize((n, n), Image.LANCZOS).save(os.path.join(EXT_DIR, "icons", f"icon{n}.png"))
    for n in (48, 64):
        logo.resize((n, n), Image.LANCZOS).save(os.path.join(BRAND_DIR, f"logo_{n}.png"))
    big.save(os.path.join(BRAND_DIR, "logo.ico"), format="ICO",
             sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])

    data = {k: b.get(k, "") for k in ("app_name", "creator", "facebook", "github", "whatsapp", "version")}
    with open(os.path.join(EXT_DIR, "branding.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/make_assets.py from branding/branding.json. Do not edit.\n")
        f.write("var BRAND = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n")

    mpath = os.path.join(EXT_DIR, "manifest.json")
    with open(mpath, encoding="utf-8") as f:
        m = json.load(f)
    m["name"] = data["app_name"]
    m["version"] = data["version"]
    m["description"] = ("Download videos from YouTube and other supported sites in up to 4K. "
                        "Only for content you own or have permission to download.")
    m.setdefault("action", {})["default_title"] = data["app_name"]
    with open(mpath, "w", encoding="utf-8") as f:
        json.dump(m, f, indent=2, ensure_ascii=False)
        f.write("\n")

    def q(x):
        return str(x).replace('"', "")
    url = next((data[k] for k in ("github", "facebook")
                if data[k].startswith("http") and "YOUR_" not in data[k]), "")
    with open(os.path.join(ROOT, "installer", "branding.iss"), "w", encoding="utf-8") as f:
        f.write(f'#define AppName "{q(data["app_name"])} Helper"\n')
        f.write(f'#define AppVersion "{q(data["version"])}"\n')
        f.write(f'#define AppPublisher "{q(data["creator"])}"\n')
        f.write(f'#define AppURL "{q(url)}"\n')

    print(f"Branding applied: {data['app_name']} by {data['creator']}")
    for key in ("facebook", "github"):
        if "YOUR_" in data[key] or not data[key]:
            print(f"  NOTE: set your real {key} link in branding/branding.json")


if __name__ == "__main__":
    main()
